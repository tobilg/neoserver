#!/usr/bin/env node
// Regenerates the Go dependency table in THIRD-PARTY-LICENSES.md from the
// modules actually linked into ./cmd/neoserver, reading each module's license
// text out of the module cache.
//
//   node scripts/third-party-licenses.mjs           # rewrite the table
//   node scripts/third-party-licenses.mjs --check   # fail if it is stale
//
// The prose around the table is hand-written and is left untouched; only the
// block between the BEGIN/END markers is generated.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const BEGIN = "<!-- BEGIN GENERATED GO MODULES -->";
const END = "<!-- END GENERATED GO MODULES -->";
const FILE = "THIRD-PARTY-LICENSES.md";

const go = (...args) =>
  execFileSync("go", args, { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

// Resolve dependencies for the release artifact, not for whatever machine runs
// this. duckdb-go-bindings is published one module per platform, so listing the
// host's would make the table differ between a developer's laptop and CI.
const RELEASE_TARGET = { GOOS: "linux", GOARCH: "amd64", CGO_ENABLED: "1" };
const goForTarget = (...args) =>
  execFileSync("go", args, {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    env: { ...process.env, ...RELEASE_TARGET },
  });

// Module cache paths escape each capital letter as "!" + the lowercase letter.
const escapeModulePath = (path) => path.replace(/[A-Z]/g, (c) => "!" + c.toLowerCase());

function detectLicense(text) {
  const head = text.slice(0, 5000);
  if (/FreeType License/i.test(head) && /GNU General Public License/i.test(head))
    return "FTL OR GPL-2.0-or-later";
  if (/Apache License/.test(head) && /Version 2\.0/.test(head)) return "Apache-2.0";
  if (/MIT License/.test(head) || /Permission is hereby granted, free of charge/.test(head))
    return "MIT";
  if (/Redistributions in binary form/.test(head) && /endorse/.test(head))
    return "BSD-3-Clause";
  if (/Redistributions in binary form/.test(head)) return "BSD-2-Clause";
  if (/Mozilla Public License/.test(head)) return "MPL-2.0";
  if (/ISC/.test(head)) return "ISC";
  return "UNKNOWN";
}

const cache = go("env", "GOMODCACHE").trim();
const modules = goForTarget(
  "list",
  "-deps",
  "-f",
  "{{with .Module}}{{.Path}} {{.Version}}{{end}}",
  "./cmd/neoserver",
)
  .split("\n")
  .map((line) => line.trim().split(/\s+/))
  .filter((parts) => parts.length === 2)
  .sort((a, b) => a[0].localeCompare(b[0]));

const seen = new Map();
const problems = [];
for (const [path, version] of modules) {
  if (seen.has(path + version)) continue;
  const dir = join(cache, escapeModulePath(path) + "@" + version);
  const file = existsSync(dir)
    ? readdirSync(dir).find((name) => /^(LICENSE|COPYING|LICENCE)/i.test(name))
    : undefined;
  if (!file) {
    problems.push(`${path} ${version}: no license file in the module cache`);
    continue;
  }
  const license = detectLicense(readFileSync(join(dir, file), "utf8"));
  if (license === "UNKNOWN") problems.push(`${path} ${version}: unrecognized license text`);
  const notice = readdirSync(dir).some((name) => /^NOTICE/i.test(name));
  seen.set(path + version, { path, version, license, notice });
}

const rows = [...seen.values()];
const platform = `${RELEASE_TARGET.GOOS}/${RELEASE_TARGET.GOARCH}`;
const table = [
  `Generated by \`node scripts/third-party-licenses.mjs\` from the ${rows.length} modules linked into \`./cmd/neoserver\` for the ${platform} release target. "NOTICE" marks a module shipping its own NOTICE file, whose contents are reproduced above. A native build for another platform substitutes the matching \`duckdb-go-bindings\` module, which carries the same MIT license.`,
  "",
  "| Module | Version | License | NOTICE |",
  "| --- | --- | --- | --- |",
  ...rows.map(
    (r) => `| \`${r.path}\` | ${r.version} | ${r.license} | ${r.notice ? "yes" : ""} |`,
  ),
].join("\n");

const current = readFileSync(FILE, "utf8");
const start = current.indexOf(BEGIN);
const end = current.indexOf(END);
if (start === -1 || end === -1) {
  console.error(`${FILE}: missing ${BEGIN} / ${END} markers`);
  process.exit(1);
}
const updated =
  current.slice(0, start + BEGIN.length) + "\n\n" + table + "\n\n" + current.slice(end);

if (process.argv.includes("--check")) {
  if (updated !== current) {
    console.error(`${FILE} is out of date. Run: node scripts/third-party-licenses.mjs`);
    process.exit(1);
  }
  console.log(`${FILE} is up to date (${rows.length} modules).`);
} else {
  writeFileSync(FILE, updated);
  console.log(`${FILE}: wrote ${rows.length} modules.`);
}

if (problems.length) {
  console.error("\nNeeds a human decision:");
  for (const p of problems) console.error("  " + p);
  process.exit(1);
}
